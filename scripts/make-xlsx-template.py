# Builds the BLANK company-style template that the app fills when you press "Download the Excel":
# tabs "Resumen" and "Reporte detallado", the same columns and colors as the company's file, a table with filter arrows,
# banded rows and a date column. Writes src/lib/xlsx-template.ts (the file embedded as base64). Usage: python3 scripts/make-xlsx-template.py
import base64, io
from openpyxl import Workbook
from openpyxl.styles import PatternFill, Font, Alignment, Border, Side
from openpyxl.worksheet.table import Table, TableStyleInfo

red = PatternFill("solid", fgColor="C00000")
black = PatternFill("solid", fgColor="000000")
gray = PatternFill("solid", fgColor="D9D9D9")
thin = Side(style="thin", color="BFBFBF")
box = Border(left=thin, right=thin, top=thin, bottom=thin)

wb = Workbook()
rs = wb.active
rs.title = "Resumen"
rs.merge_cells("A1:F1")
rs["A1"] = "RESUMEN DE CLASES EXTRACURRICULARES"
rs["A1"].font = Font(name="Cambria", size=24, bold=True, color="FFF2CC")
rs["A1"].fill = red
rs["A1"].alignment = Alignment(horizontal="left", vertical="center")
rs.row_dimensions[1].height = 40
for i, h in enumerate(["Docente", "Mes-Año", "Horas Perdidas", "Horas Recuperadas", "Horas Extra", "Colaboraciones"], start=1):
    c = rs.cell(row=2, column=i, value=h)
    c.fill = red; c.font = Font(bold=True, color="FFFFFF", size=12); c.alignment = Alignment(horizontal="center", vertical="center")
    d = rs.cell(row=3, column=i)
    d.fill = gray; d.border = box; d.alignment = Alignment(horizontal="left" if i <= 2 else "center", vertical="center")
    d.number_format = "General"
rs.row_dimensions[2].height = 24
rs.row_dimensions[3].height = 24
t1 = Table(displayName="Tabla1", ref="A2:F3")
t1.tableStyleInfo = TableStyleInfo(name=None, showRowStripes=False)
rs.add_table(t1)
for col, w in zip("ABCDEF", [26, 16, 18, 20, 14, 18]):
    rs.column_dimensions[col].width = w

rd = wb.create_sheet("Reporte detallado")
heads = ["Fecha", "Horario", "Grupo o estudiante", "Tipo de clase", "Solicitud", "Evidencia", "Información adicional y detalles"]
for i, h in enumerate(heads, start=1):
    c = rd.cell(row=1, column=i, value=h)
    c.fill = black; c.font = Font(bold=True, color="FFFFFF", size=12); c.alignment = Alignment(vertical="center")
rd.row_dimensions[1].height = 24
for r in range(2, 101):  # 99 pre-formatted rows, banded like the company's file (even rows gray)
    for ci in range(1, 8):
        c = rd.cell(row=r, column=ci)
        c.border = box
        c.alignment = Alignment(vertical="center", wrap_text=(ci == 7), horizontal="right" if ci == 1 else "left")
        if ci == 1:
            c.number_format = "d-mmm-yy"
        if ci == 6:
            c.font = Font(color="0563C1", underline="single")
        if r % 2 == 0:
            c.fill = gray
t2 = Table(displayName="Tabla2", ref="A1:G2")
t2.tableStyleInfo = TableStyleInfo(name=None, showRowStripes=False)
rd.add_table(t2)
for col, w in zip("ABCDEFG", [12, 16, 22, 16, 18, 34, 60]):
    rd.column_dimensions[col].width = w
rd.freeze_panes = "A2"
for ws in (rs, rd):  # prints on one page wide, landscape
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True

buf = io.BytesIO()
wb.save(buf)
b64 = base64.b64encode(buf.getvalue()).decode()
lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
with open("src/lib/xlsx-template.ts", "w", encoding="utf-8") as f:
    f.write("// GENERATED by scripts/make-xlsx-template.py — do not edit by hand.\n")
    f.write("// The blank company-style workbook (tabs Resumen + Reporte detallado) that \"Download the Excel\" fills in.\n")
    f.write("// To use the company's own file instead, replace this base64 with theirs (any .xlsx with those two tabs works).\n")
    f.write("const B64 = [\n" + ",\n".join(f'  "{l}"' for l in lines) + ",\n].join(\"\");\n\n")
    f.write("export function templateBytes(): Uint8Array {\n  return new Uint8Array(Buffer.from(B64, \"base64\"));\n}\n")
print("template bytes:", len(buf.getvalue()))
