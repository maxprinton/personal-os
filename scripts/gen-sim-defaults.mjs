// Reads supabase/migrations/*.sql and writes src/lib/bot/sim/defaults.ts: the column defaults of every table,
// so the Telegram simulator can fill the columns a real insert would fill (status 'open', created_at…).
// Run again after adding a migration:  node scripts/gen-sim-defaults.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
/** @type {Record<string, Record<string, unknown>>} */
const out = {};

function literal(raw) {
  let v = raw.trim().replace(/[;,]\s*$/, "").trim();
  v = v.replace(/^\((.*)\)$/s, "$1").trim();
  if (/^(now\(\)|current_timestamp|timezone\(.*|\(?now\(\).*)/i.test(v)) return "$now";
  if (/^current_date/i.test(v) || /^\(?now\(\)::date/i.test(v)) return "$today";
  if (/^(gen_random_uuid|uuid_generate_v4)\(\)/i.test(v)) return "$uuid";
  if (/^auth\.uid\(\)/i.test(v)) return undefined;
  if (/^(true|false)$/i.test(v)) return v.toLowerCase() === "true";
  if (/^-?\d+(\.\d+)?$/.test(v)) return Number(v);
  let m = /^'((?:[^']|'')*)'(?:::[a-z_ \[\]0-9]+)?$/is.exec(v);
  if (m) {
    const s = m[1].replace(/''/g, "'");
    if (/::jsonb?$/i.test(v)) { try { return JSON.parse(s); } catch { return undefined; } }
    if (s === "{}" && /\[\]$/.test(v)) return [];
    return s;
  }
  if (/^array\[\s*\](::[a-z_ \[\]0-9]+)?$/i.test(v)) return [];
  return undefined;
}

function column(table, line) {
  const m = /^\s*([a-z_][a-z0-9_]*)\s+(?!primary|unique|check|constraint|foreign)[a-z_][a-z0-9_ ()\[\],]*?\bdefault\s+(.+?)\s*(?:,?\s*)$/i.exec(line);
  if (!m) return;
  // cut at the next constraint keyword
  const raw = m[2].replace(/\s+(not null|null|check|references|primary key|unique)\b.*$/i, "");
  const val = literal(raw);
  if (val !== undefined) (out[table] ??= {})[m[1]] = val;
}

for (const f of files) {
  const sql = readFileSync(join(dir, f), "utf8").replace(/--.*$/gm, "");
  for (const t of sql.matchAll(/create table(?: if not exists)? (?:public\.)?([a-z_0-9]+)\s*\(([\s\S]*?)\n\);/gi)) {
    for (const line of t[2].split("\n")) column(t[1], line);
  }
  for (const a of sql.matchAll(/alter table(?: if exists)?(?: only)? (?:public\.)?([a-z_0-9]+)\s+add column(?: if not exists)?\s+([^;]+);/gi)) {
    column(a[1], a[2].replace(/\s+/g, " ").replace(/^/, "  "));
  }
}

const body = Object.keys(out).sort().map((t) => `  ${t}: ${JSON.stringify(out[t])},`).join("\n");
writeFileSync(
  "src/lib/bot/sim/defaults.ts",
  `// GENERATED by scripts/gen-sim-defaults.mjs from supabase/migrations — do not edit by hand.\n// "$now", "$today" and "$uuid" are filled in when a row is created.\nexport const DEFAULTS: Record<string, Record<string, unknown>> = {\n${body}\n};\n`,
);
console.log(`defaults for ${Object.keys(out).length} tables`);
